"""يولّد www/i18n.js من ملفات الترجمة.
- keys.json + en_indexed.txt: النصوص العربية المجمّعة من التطبيق وترجمتها (رقم|ترجمة)، والأرقام تُستبدل بـ {n}
- en_extra.txt: نص عربي|ترجمة (للنصوص الإضافية: الصوت، الرسائل، الإشعارات)
- en_patterns.txt: أنماط فيها {s} لنص متغيّر يُترجم بدوره
- fem_words.txt / fem_phrases.txt: تحويل الخطاب للمؤنث (كلمة كاملة / عبارة)
تشغيل: python3 i18n/build.py
"""
import json,re,os
H=os.path.dirname(os.path.abspath(__file__))
rd=lambda f:[l.rstrip('\n') for l in open(os.path.join(H,f),encoding='utf-8') if '|' in l]
norm=lambda k:re.sub(r'\d+([.:,]\d+)*','{n}',re.sub(r'\s+',' ',k).strip())
keys=json.load(open(os.path.join(H,'keys.json'),encoding='utf-8'))
en={}
for l in rd('en_indexed.txt'):
    i,v=l.split('|',1)
    if v: en[keys[int(i)]]=v
for l in rd('en_extra.txt'):
    k,v=l.split('|',1); en.setdefault(norm(k),v)
pat=[l.split('|',1) for l in rd('en_patterns.txt')]
fw=dict(l.split('|',1) for l in rd('fem_words.txt'))
fp=[l.split('|',1) for l in rd('fem_phrases.txt')]
# فحوص السلامة: يتوقف التوليد إن وُجد خلل يُفقد ترجمة أو يُنتج نصًا ناقصًا
err=[]
for a,b in pat:
    if a.count('{s}')!=b.count('{s}') or a.count('{n}')!=b.count('{n}'): err.append('نمط غير متطابق: '+a)
for k,v in en.items():
    if v.count('{n}')>k.count('{n}'): err.append('الترجمة تطلب أرقامًا غير موجودة: '+k)
    if not v.strip(): err.append('ترجمة فارغة: '+k)
for f in ('en_extra.txt','fem_words.txt','fem_phrases.txt'):
    seen={}
    for l in rd(f):
        k=l.split('|',1)[0]
        if k in seen and seen[k]!=l: err.append(f+': مفتاح مكرر بترجمتين مختلفتين: '+k)
        seen[k]=l
if err:
    print('\n'.join(err)); raise SystemExit('i18n check failed: %d' % len(err))
out='/* Vigoris i18n — generated by i18n/build.py, do not edit by hand */\nwindow.I18N='+json.dumps({'en':en,'enPat':pat,'femW':fw,'femP':fp},ensure_ascii=False)+';\n'
open(os.path.join(H,'..','www','i18n.js'),'w',encoding='utf-8').write(out)
print('en',len(en),'patterns',len(pat),'fem',len(fw),len(fp))
